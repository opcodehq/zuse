//! Bash-like glob handling for Claude's Bash tool when the user's shell is zsh.
//!
//! Claude runs its Bash tool in `$SHELL` when that names bash or zsh. Models
//! write bash, and zsh's default `NOMATCH` turns an unquoted pattern with no
//! matches (`grep -rn foo --include=*.ts`) into "no matches found" before the
//! command runs. A tiny wrapper that execs the same zsh with `-o NO_NOMATCH`
//! is exposed through `CLAUDE_CODE_SHELL`; its name still contains `zsh`, so
//! Claude keeps its zsh-specific setup (rc snapshot, per-command options).

use std::ffi::OsStr;
use std::path::{Path, PathBuf};

use sha2::{Digest, Sha256};

use crate::process::Command;

const OVERRIDE: &str = "CLAUDE_CODE_SHELL";

/// The zsh Claude would run its Bash tool in: an absolute `$SHELL` naming zsh,
/// unless the user already chose a shell through `CLAUDE_CODE_SHELL`.
pub(super) fn zsh_target(
    shell: Option<&OsStr>,
    shell_override: Option<&OsStr>,
    windows: bool,
) -> Option<PathBuf> {
    let set = |value: Option<&OsStr>| value.is_some_and(|v| !v.to_string_lossy().trim().is_empty());
    if windows || set(shell_override) {
        return None;
    }
    let shell = shell?.to_str()?.trim();
    if !shell.starts_with('/') {
        return None;
    }
    let name = &shell[shell.rfind('/').map_or(0, |i| i + 1)..];
    (name.contains("zsh") && !name.contains("bash")).then(|| PathBuf::from(shell))
}

fn shell_quote(value: &str) -> String {
    format!("'{}'", value.replace('\'', r"'\''"))
}

pub(super) fn wrapper_script(zsh: &Path) -> String {
    format!(
        "#!/bin/sh\n# Generated by Zuse for Claude Code's Bash tool.\nexec {} -o NO_NOMATCH \"$@\"\n",
        shell_quote(&zsh.to_string_lossy())
    )
}

fn wrapper_dir() -> Option<PathBuf> {
    crate::executable::home_dir().map(|home| home.join(".zuse").join("provider-shells"))
}

/// Write (or reuse) the wrapper for `zsh` in `dir`, atomically and mode 0700.
#[cfg(unix)]
pub(super) fn ensure_wrapper(zsh: &Path, dir: &Path) -> std::io::Result<PathBuf> {
    use std::io::Write;
    use std::os::unix::fs::{DirBuilderExt, OpenOptionsExt, PermissionsExt};

    let script = wrapper_script(zsh);
    let digest = Sha256::digest(zsh.as_os_str().as_encoded_bytes());
    let id: String = digest.iter().map(|b| format!("{b:02x}")).collect();
    // Claude only accepts an override whose file name names zsh.
    let file = dir.join(format!("zsh-{}", &id[..12]));
    let executable = std::fs::Permissions::from_mode(0o700);
    if std::fs::read_to_string(&file).is_ok_and(|current| current == script) {
        std::fs::set_permissions(&file, executable)?;
        return Ok(file);
    }
    std::fs::DirBuilder::new()
        .recursive(true)
        .mode(0o700)
        .create(dir)?;
    let temp = dir.join(format!("zsh-{}.{}.tmp", &id[..12], uuid::Uuid::new_v4()));
    let installed = (|| {
        let mut out = std::fs::OpenOptions::new()
            .write(true)
            .create_new(true)
            .mode(0o700)
            .open(&temp)?;
        out.write_all(script.as_bytes())?;
        out.sync_all()?;
        // The creation mode is masked by the umask; the wrapper must be executable.
        std::fs::set_permissions(&temp, executable)?;
        std::fs::rename(&temp, &file)
    })();
    if let Err(error) = installed {
        let _ = std::fs::remove_file(&temp);
        return Err(error);
    }
    Ok(file)
}

/// Point Claude at the NO_NOMATCH zsh wrapper when zsh is the user's shell.
/// Any failure leaves the command's environment unchanged, so session start
/// never depends on it.
pub(super) fn apply(cmd: &mut Command) {
    #[cfg(unix)]
    {
        let explicit = |key: &str| {
            cmd.as_std()
                .get_envs()
                .find(|(k, _)| *k == OsStr::new(key))
                .map(|(_, v)| v.map(OsStr::to_os_string))
        };
        // An env set (or removed) on the command wins over the inherited one.
        let value = |key: &str| explicit(key).unwrap_or_else(|| std::env::var_os(key));
        let (shell, shell_override) = (value("SHELL"), value(OVERRIDE));
        let Some(zsh) = zsh_target(shell.as_deref(), shell_override.as_deref(), false) else {
            return;
        };
        let Some(dir) = wrapper_dir() else { return };
        match ensure_wrapper(&zsh, &dir) {
            Ok(file) => {
                cmd.env(OVERRIDE, file);
            }
            Err(error) => {
                tracing::debug!(target: "zuse_providers::claude", "zsh wrapper unavailable: {error}");
            }
        }
    }
    #[cfg(not(unix))]
    let _ = (cmd, wrapper_dir);
}

#[cfg(test)]
mod tests {
    use super::*;

    fn target(shell: Option<&str>, shell_override: Option<&str>, windows: bool) -> Option<PathBuf> {
        zsh_target(
            shell.map(OsStr::new),
            shell_override.map(OsStr::new),
            windows,
        )
    }

    #[test]
    fn targets_only_an_absolute_zsh_login_shell() {
        assert_eq!(
            target(Some("/bin/zsh"), None, false),
            Some("/bin/zsh".into())
        );
        assert_eq!(
            target(Some("/opt/homebrew/bin/zsh"), None, false),
            Some("/opt/homebrew/bin/zsh".into())
        );
        assert_eq!(target(Some("/bin/bash"), None, false), None);
        assert_eq!(target(Some("zsh"), None, false), None);
        assert_eq!(target(None, None, false), None);
        assert_eq!(target(Some("/bin/zsh"), None, true), None);
    }

    #[test]
    fn respects_an_explicit_shell_override() {
        assert_eq!(target(Some("/bin/zsh"), Some("/bin/bash"), false), None);
        assert_eq!(
            target(Some("/bin/zsh"), Some("  "), false),
            Some("/bin/zsh".into())
        );
    }

    #[test]
    fn quotes_the_zsh_path_in_the_wrapper() {
        assert!(
            wrapper_script(Path::new("/Users/o'neil/bin/zsh"))
                .contains(r#"exec '/Users/o'\''neil/bin/zsh' -o NO_NOMATCH "$@""#)
        );
    }

    #[cfg(unix)]
    #[test]
    fn fails_without_side_effects_when_the_dir_is_blocked() {
        let dir = tempfile::tempdir().unwrap();
        let blocked = dir.path().join("file");
        std::fs::write(&blocked, "").unwrap();
        assert!(ensure_wrapper(Path::new("/bin/zsh"), &blocked.join("x")).is_err());
    }

    #[cfg(unix)]
    #[test]
    fn removes_the_temporary_wrapper_when_installing_fails() {
        let dir = tempfile::tempdir().unwrap();
        let wrapper = ensure_wrapper(Path::new("/bin/zsh"), dir.path()).unwrap();
        std::fs::remove_file(&wrapper).unwrap();
        std::fs::create_dir_all(wrapper.join("occupied")).unwrap();
        assert!(ensure_wrapper(Path::new("/bin/zsh"), dir.path()).is_err());
        let leftovers: Vec<_> = std::fs::read_dir(dir.path())
            .unwrap()
            .filter_map(|e| e.ok())
            .filter(|e| e.file_name().to_string_lossy().ends_with(".tmp"))
            .collect();
        assert!(leftovers.is_empty());
    }

    #[cfg(unix)]
    #[test]
    fn writes_an_executable_wrapper_and_reuses_it() {
        use std::os::unix::fs::PermissionsExt;
        let dir = tempfile::tempdir().unwrap();
        let wrapper = ensure_wrapper(Path::new("/bin/zsh"), dir.path()).unwrap();
        let name = wrapper.file_name().unwrap().to_string_lossy().into_owned();
        assert!(name.starts_with("zsh-") && name.len() == "zsh-".len() + 12);
        let mode = std::fs::metadata(&wrapper).unwrap().permissions().mode();
        assert_eq!(mode & 0o777, 0o700);
        assert_eq!(
            std::fs::read_to_string(&wrapper).unwrap(),
            wrapper_script(Path::new("/bin/zsh"))
        );
        // A stale mode is repaired on reuse; the path stays the same.
        std::fs::set_permissions(&wrapper, std::fs::Permissions::from_mode(0o600)).unwrap();
        assert_eq!(
            ensure_wrapper(Path::new("/bin/zsh"), dir.path()).unwrap(),
            wrapper
        );
        let mode = std::fs::metadata(&wrapper).unwrap().permissions().mode();
        assert_eq!(mode & 0o777, 0o700);
    }

    #[cfg(unix)]
    #[test]
    fn passes_unmatched_globs_through_like_bash() {
        if !Path::new("/bin/zsh").exists() {
            return;
        }
        let dir = tempfile::tempdir().unwrap();
        let wrapper = ensure_wrapper(Path::new("/bin/zsh"), dir.path()).unwrap();
        let output = std::process::Command::new(&wrapper)
            .args(["-c", "echo --include=*.zuse-no-such-ext"])
            .current_dir(dir.path())
            .output()
            .unwrap();
        assert_eq!(
            String::from_utf8_lossy(&output.stdout).trim(),
            "--include=*.zuse-no-such-ext"
        );
    }

    #[cfg(unix)]
    #[test]
    fn apply_leaves_bash_commands_unchanged() {
        let mut cmd = Command::new("claude");
        cmd.env("SHELL", "/bin/bash");
        apply(&mut cmd);
        assert!(
            !cmd.as_std()
                .get_envs()
                .any(|(k, _)| k == OsStr::new(OVERRIDE))
        );
    }

    #[cfg(unix)]
    #[test]
    fn apply_respects_an_override_set_on_the_command() {
        let mut cmd = Command::new("claude");
        cmd.env("SHELL", "/bin/zsh").env(OVERRIDE, "/bin/bash");
        apply(&mut cmd);
        let value = cmd
            .as_std()
            .get_envs()
            .find(|(k, _)| *k == OsStr::new(OVERRIDE))
            .and_then(|(_, v)| v);
        assert_eq!(value, Some(OsStr::new("/bin/bash")));
    }
}

//! Generate the public SDK contracts from Rust. Run with --check in CI.
use ts_rs::TS;
use zuse_protocol::{control::*, zots::*};
fn main() {
    let sdk = std::path::Path::new(env!("CARGO_MANIFEST_DIR")).join("../../packages/sdk");
    for manifest in ["package.json", "package-lock.json"] {
        let package: serde_json::Value = serde_json::from_str(
            &std::fs::read_to_string(sdk.join(manifest)).expect("SDK manifest missing"),
        )
        .expect("invalid SDK manifest");
        assert_eq!(
            package["version"].as_str(),
            Some(env!("CARGO_PKG_VERSION")),
            "{manifest}: SDK and control binary versions must match"
        );
        if manifest == "package-lock.json" {
            assert_eq!(
                package["packages"][""]["version"], package["version"],
                "SDK lockfile root version is stale"
            );
        }
    }

    let mut text = String::from(
        "// Generated by cargo run -p zuse-protocol --example control_types.\n// Do not edit by hand.\n",
    );
    macro_rules! emit { ($($ty:ty),*) => { $(text.push_str(&format!("export {}\n", <$ty>::decl()));)* }; }
    emit!(
        ZotRepository,
        ZotAvatar,
        ZotModel,
        ZotConfig,
        ZotStatus,
        ZotWorker,
        ZotDecision,
        ZotIssueStatus,
        ZotIssuePriority,
        ZotIssueDetails,
        ZotIssuePullRequest,
        ZotIssueActivity,
        ZotIssue,
        Zot,
        ZotFile,
        ZotAction,
        ZotCommand,
        ZotEvent,
        ControlInfo
    );
    text.push_str(&format!(
        "export const API_VERSION = {API_VERSION} as const;\n"
    ));
    text.push_str(&format!(
        "export const METHODS = {} as const;\n",
        serde_json::to_string(zuse_protocol::control::METHODS).unwrap()
    ));
    text.push_str("export type ControlMethod = typeof METHODS[number];\n");
    let text = text
        .lines()
        .map(str::trim_end)
        .collect::<Vec<_>>()
        .join("\n")
        + "\n";
    let path = std::path::Path::new(env!("CARGO_MANIFEST_DIR"))
        .join("../../packages/sdk/src/generated.ts");
    if std::env::args().any(|arg| arg == "--check") {
        assert_eq!(
            std::fs::read_to_string(path).expect("generated SDK contracts missing"),
            text,
            "SDK contracts are stale"
        );
    } else {
        std::fs::create_dir_all(path.parent().unwrap()).unwrap();
        std::fs::write(path, text).unwrap();
    }
}

"""Share the desktop's mascot definitions with the browser, so both draw the same Zappers."""
from pathlib import Path
import json, re
root = Path(__file__).resolve().parents[3]
source = (root / 'crates/protocol/src/presentation/zapper_mascots.rs').read_text()
num = r'(-?[0-9.]+)'
def eyes(text):
    return [dict(shape='capsule' if kind == 'capsule' else 'oval', x=float(x), y=float(y), w=float(w), h=float(h))
            for kind, x, y, w, h in re.findall(rf'(capsule|oval)\(\s*{num},\s*{num},\s*{num},\s*{num},?\s*\)', text)]
mascots = []
for match in re.finditer(r'Mascot \{\s*id: "([^"]+)",\s*name: "([^"]+)",\s*about: "([^"]+)",.*?body: Body \{(.*?)temper: Temper::(\w+)', source, re.S):
    id, name, about, body, temper = match.groups()
    field = lambda key: float(re.search(rf'\b{key}: {num},', body).group(1))
    mascots.append(dict(id=id, name=name, about=about, a=field('a'), b=field('b'), n=field('n'), taper=field('taper'), dy=field('dy'), eyes=eyes(body), temper=temper.lower()))
colors = [dict(id=id, body=f'#{body}', shade=f'#{shade}') for id, body, shade in re.findall(r'MascotColor \{\s*id: "([^"]+)",\s*body: 0x([0-9a-f]+),\s*shade: 0x([0-9a-f]+)', source)]
intervals = {name.lower(): [int(v) for v in values.split(',') if v.strip()] for name, values in re.findall(r'Temper::(\w+) => &\[([0-9, ]+)\]', source)}
eye = '#' + re.search(r'pub const EYE: u32 = 0x([0-9a-f]+);', source).group(1)
assert len(mascots) == 9 and colors and all(len(m['eyes']) == 2 for m in mascots) and set(intervals) == {m['temper'] for m in mascots} | set(intervals)
out = root / 'apps/web-solid/src/features/zappers/mascots.ts'
out.write_text('// Generated by scripts/gen-zapper-mascots.py from crates/protocol/src/presentation/zapper_mascots.rs.\n'
  + 'export type Temper = ' + ' | '.join(json.dumps(t) for t in intervals) + ';\n'
  + 'export type Mascot = { id: string; name: string; about: string; a: number; b: number; n: number; taper: number; dy: number; eyes: { shape: "capsule" | "oval"; x: number; y: number; w: number; h: number }[]; temper: Temper };\n'
  + 'export const mascots: Mascot[] = ' + json.dumps(mascots, indent=2) + ';\n'
  + 'export const colors = ' + json.dumps(colors, indent=2) + ';\n'
  + 'export const blinkGaps: Record<Temper, number[]> = ' + json.dumps(intervals) + ';\n'
  + 'export const EYE = ' + json.dumps(eye) + ';\n')

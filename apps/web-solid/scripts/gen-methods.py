#!/usr/bin/env python3
"""Generate src/core/methods.ts from the Rust protocol method names."""
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[3]
PROTOCOL = ROOT / 'crates/protocol/src'
CONST = re.compile(r'pub const ([A-Z0-9_]+): &str = "([^"]+)";')

def consts(path, prefix=''):
    return {prefix + name: value for name, value in CONST.findall(path.read_text())}

names = consts(PROTOCOL / 'methods.rs')
names |= consts(PROTOCOL / 'project_creation.rs', 'PROJECT_')
catalog = PROTOCOL / 'custom_acp' / 'catalog.rs'
if catalog.exists():
    names |= consts(catalog, 'ACP_CATALOG_')

source = (PROTOCOL / 'methods.rs').read_text()
body = source[source.index('pub fn retryable_read'):]
body = body[:body.index('=> true')]
retryable = []
for token in re.findall(r'(?:crate::(\w+)::(?:\w+::)?)?([A-Z][A-Z0-9_]+)', body):
    module, name = token
    key = {'project_creation': 'PROJECT_' + name, 'custom_acp': 'ACP_CATALOG_' + name}.get(module, name)
    if key in names:
        retryable.append(names[key])

lines = ['// Generated by scripts/gen-methods.py from crates/protocol. Do not edit.', '', 'export const M = {']
lines += [f'  {name}: {value!r},'.replace("'", '"') for name, value in sorted(names.items())]
lines += ['} as const', '', 'export type Method = (typeof M)[keyof typeof M]', '',
          '/** Reads that may be repeated after a dropped connection. Everything else is a mutation. */',
          'const RETRYABLE = new Set<string>([']
lines += [f'  "{value}",' for value in sorted(set(retryable))]
lines += [']);', '',
          'export function retryableRead(method: string, params: unknown): boolean {',
          f'  if (method === "{names["PLUGINS"]}") return (params as {{ action?: unknown }} | undefined)?.action === "list";',
          '  return RETRYABLE.has(method);', '}', '']
(Path(__file__).resolve().parents[1] / 'src/core/methods.ts').write_text('\n'.join(lines))
print(len(names), 'methods,', len(set(retryable)), 'retryable')

import assert from "node:assert/strict";
import { fileURLToPath } from "node:url";
import { createServer } from "vite";
import { openBrowser } from "./harness.mjs";
const app = fileURLToPath(new URL("..", import.meta.url));
const server = await createServer({ root: app, configFile: `${app}/vite.config.ts`, server: { host: "127.0.0.1", port: 0, open: false } });
await server.listen();
let page;
try {
  page = await openBrowser(`http://127.0.0.1:${server.httpServer.address().port}/e2e/web-parity/fixture.html`);
  await page.waitFor("!!window.parity && !!document.querySelector('#workspace')");
  assert.equal(await page.eval("parity.icons()"), true);
  await page.eval("parity.hosted()");
  await page.waitFor("document.body.textContent.includes('Start building from your browser')");
  await page.eval("[...document.querySelectorAll('button')].find(b => b.textContent === 'Get started').click()");
  await page.waitFor("document.querySelector('h1')?.textContent === 'Sign in to Zuse'");
  await page.eval("parity.local()");
  await page.waitFor("!!document.querySelector('#workspace')");
  await page.eval("parity.agents()");
  await page.waitFor("document.body.textContent.includes('Subagent streamed reply')");
  const calls = await page.eval("parity.counters().requests");
  const watch = calls.find(row => row.method === "WatchDocMessages");
  assert.deepEqual(watch.params, { chatId: "parent--sub--worker", targetDeviceId: "remote" });
  await page.eval("parity.reconnect()");
  await page.waitFor("parity.counters().cancellations > 0");
  await page.eval("parity.hide()");
  const before = await page.eval("parity.counters().requests.filter(r => r.method === 'WatchDocMessages').length");
  await page.eval("parity.snapshot()");
  await page.waitFor("document.body.textContent.includes('Subagent streamed reply')");
  assert.equal(await page.eval("parity.counters().requests.filter(r => r.method === 'WatchDocMessages').length"), before);
  const transport = await page.eval("checkCloudTransport()");
  const forwarded = transport.frames.find(frame => frame.method === "CloudRpc");
  assert.equal(forwarded.params.workspaceId, "workspace");
  assert.equal(forwarded.params.expectedAccountId, "actor");
  assert.equal(forwarded.params.method, "WatchChats");
  assert.deepEqual(transport.replies[0], { id: 42, ok: { result: "engine reply" } });
  assert(transport.frames.some(frame => frame.id === forwarded.id && frame.cancel));
  assert.equal(typeof transport.frames.find(frame => frame.method === "CloudRpc" && frame.params.method === "QueueMessage").params.logicalCommandId, "string");
  assert.equal(transport.revoked, true);
  assert(transport.closes > 0);
  console.log("PASS cloud RPC routing, cancellation, account revocation; web onboarding isolation, desktop icons, live agent feed, reconnect cleanup, frozen agent history");
} finally { await page?.close(); await server.close(); }

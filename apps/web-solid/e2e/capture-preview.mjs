import { createServer } from 'vite';
import { openBrowser } from './harness.mjs';
import { mkdirSync, writeFileSync } from 'node:fs';
const root = new URL('..', import.meta.url).pathname;
const out = process.env.ZUSE_PREVIEW_OUT ?? new URL('../../../artifacts/web-preview', import.meta.url).pathname;
mkdirSync(out, { recursive: true });
const server = await createServer({ root, configFile: `${root}/vite.config.ts`, server: { host:'127.0.0.1', port:0 } });
await server.listen();
let page;
try {
 page = await openBrowser(`http://127.0.0.1:${server.httpServer.address().port}/e2e/web-parity/fixture.html`, { width:1280, height:820 });
 await page.waitFor('!!window.parity');
 await page.eval(`(async () => { await import('/src/shell/shell.css'); await import('/src/shell/theme.ts'); document.documentElement.dataset.theme = 'dark'; document.querySelector('#root > span')?.remove(); })()`);
 await page.eval('parity.hosted()');
 await page.waitFor("document.querySelector('h1')?.textContent.includes('Your workspace')");
 await page.screenshot(`${out}/onboarding.png`);
 await page.eval("document.querySelector('.web-onboarding-primary').click()");
 await page.waitFor("document.querySelector('h1')?.textContent === 'Make yourself at home.'");
 await page.screenshot(`${out}/sign-in.png`);
 await page.eval('parity.workspace()');
 await page.waitFor("!!document.querySelector('.app') && !!document.querySelector('.cmp-model')");
 await page.waitFor("!!document.querySelector('.ws-agent-row')");
 await page.screenshot(`${out}/workspace.png`);
 await page.screenshot(`${out}/agents.png`);
 await page.click('.cmp-model');
 await page.waitFor("!!document.querySelector('.cmp-models')");
 await page.waitFor("document.querySelectorAll('.cmp-model-row').length > 0");
 await page.screenshot(`${out}/model-picker.png`);
 const opus = await page.eval("(() => { const row=[...document.querySelectorAll('.cmp-model-row')].find(row=>row.textContent.includes('Opus 4.6')); const box=row.getBoundingClientRect(); return {x:box.x+box.width/2,y:box.y+box.height/2}; })()");
 await page.call('Input.dispatchMouseEvent',{type:'mouseMoved',...opus});
 await page.waitFor("document.querySelector('.cmp-detail-header')?.textContent.includes('Opus 4.6') && !!document.querySelector('.cmp-detail-context')");
 await page.screenshot(`${out}/model-picker-context.png`);
 const cardClip = await page.eval("(() => { const box=document.querySelector('.cmp-model-detail').getBoundingClientRect(); return {x:box.x-8,y:box.y-8,width:box.width+16,height:box.height+16,scale:1}; })()");
 const cardImage = await page.call('Page.captureScreenshot',{format:'png',clip:cardClip});
 writeFileSync(`${out}/reasoning-card.png`,Buffer.from(cardImage.result.data,'base64'));
 await page.click('.cmp-model');
 await page.waitFor("!document.querySelector('.cmp-models')");
 await page.eval('parity.zapper()');
 await page.waitFor("document.querySelectorAll('.zp-issue-row').length === 2 && !document.querySelector('.app-right')");
 await page.click('.zp-tabs [aria-label="Overview"]');
 await page.waitFor("!!document.querySelector('.zp-needs-you')");
 await page.screenshot(`${out}/zapper-overview.png`);
 await page.click('.zp-tabs [aria-label="Issues"]');
 await page.waitFor("!!document.querySelector('[aria-label=\"Search Zapper issues\"]')");
 await page.screenshot(`${out}/zapper-issues.png`);
 await page.click('.zp-issue-row');
 await page.waitFor("document.querySelector('.zp-issue-page')?.textContent.includes('Done when')");
 await page.screenshot(`${out}/zapper-issue-detail.png`);
 await page.click('[aria-label="Close ZAP-12"]');
 await page.call('Emulation.setDeviceMetricsOverride',{width:720,height:900,deviceScaleFactor:1,mobile:false});
 await page.waitFor("getComputedStyle(document.querySelector('.zp-conversation')).display === 'none'");
 await page.screenshot(`${out}/zapper-narrow.png`);
 await page.eval('parity.queued(); parity.openQueued()');
 await page.click('[aria-label="Close Zapper inspector"]');
 await page.waitFor("document.querySelector('.zp-thread-placeholder')?.textContent.includes('Queued · 2')");
 await page.screenshot(`${out}/zapper-queued.png`);
 console.log(out);
} finally { await page?.close(); await server.close(); }

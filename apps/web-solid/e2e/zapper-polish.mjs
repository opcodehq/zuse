import assert from 'node:assert/strict';
import { createServer } from 'vite';
import { openBrowser } from './harness.mjs';
const root = new URL('..',import.meta.url).pathname;
const server=await createServer({root,configFile:`${root}/vite.config.ts`,server:{host:'127.0.0.1',port:0,hmr:{overlay:false}}});
await server.listen();
let page;
const clickText=async text=> page.eval(`[...document.querySelectorAll('button')].find(b=>b.textContent.trim()===${JSON.stringify(text)}).click()`);
try {
 page=await openBrowser(`http://127.0.0.1:${server.httpServer.address().port}/e2e/web-parity/fixture.html`);
 await page.waitFor('!!window.parity');
 await page.eval('parity.workspace(); parity.zapper()');
 await page.waitFor("document.querySelectorAll('.zp-issue-row').length === 2");
 await page.press('.zp-issue-row');
 await page.waitFor("document.querySelector('[role=dialog]')?.textContent.includes('Done when')");
 await page.waitFor("document.querySelector('[role=dialog]')?.contains(document.activeElement)");
 await page.key('Escape','Escape',27);
 await page.waitFor("!document.querySelector('[role=dialog]')");
 await page.press('.zp-issue-row');
 await page.waitFor("document.querySelector('[role=dialog]')?.textContent.includes('Done when')");
 await clickText('Edit issue');
 await page.waitFor("document.querySelectorAll('[role=dialog]').length === 1 && document.querySelector('[role=dialog]')?.textContent.includes('Save issue')");
 await page.eval("(() => { const input=document.querySelector('[role=dialog] input[required]');input.value='Polished model picker';input.dispatchEvent(new Event('input',{bubbles:true})); })()");
 await clickText('Save issue');
 await page.waitFor("document.querySelector('[role=dialog]')?.textContent.includes('Polished model picker') && !document.querySelector('[role=dialog]')?.textContent.includes('Save issue')");
 await page.click('[aria-label="Close dialog"]');
 await page.waitFor("!document.querySelector('[role=dialog]')");
 await page.eval("(() => {const input=document.querySelector('[aria-label=\"Search Zapper issues\"]');input.value='missing';input.dispatchEvent(new Event('input',{bubbles:true}));})()");
 await page.waitFor("document.body.textContent.includes('No matching issues')");
 await clickText('Clear filters');
 await page.waitFor("document.querySelectorAll('.zp-issue-row').length===2");
 await page.eval('parity.panels()');
 await page.waitFor("!document.querySelector('.zp-inspector')");
 await clickText('Show Zapper');
 await page.waitFor("!!document.querySelector('.zp-inspector') && !document.querySelector('.app-right')");
 await page.click('.zp-tabs [aria-label="Threads"]');
 await page.waitFor("document.body.textContent.includes('Worker threads')");
 await clickText('Delegate');
 await page.waitFor("!!document.querySelector('[aria-label=\"Worker model\"]')");
 await page.click('[aria-label="Worker model"]');
 await page.waitFor("[...document.querySelectorAll('.model-select-row')].some(row=>row.textContent.includes('GPT-5.3 Codex'))");
 await page.waitFor("document.activeElement?.getAttribute('aria-label') === 'Search models'");
 await page.key('Escape','Escape',27);
 await page.waitFor("!document.querySelector('.model-select-popover') && document.querySelector('[role=dialog]')?.textContent.includes('Delegate a task')");
 await page.click('[aria-label="Close dialog"]');
 await page.call('Emulation.setDeviceMetricsOverride',{width:720,height:900,deviceScaleFactor:1,mobile:false});
 await page.waitFor("document.querySelector('.zp-conversation') && getComputedStyle(document.querySelector('.zp-conversation')).display === 'none'");
 await page.click('[aria-label="Close Zapper inspector"]');
 await page.waitFor("!document.querySelector('.zp-inspector') && getComputedStyle(document.querySelector('.zp-conversation')).display !== 'none'");
 console.log('PASS Zapper issue edit/save with one dialog, criteria, search/reset, inspector switching, worker model catalog');
} finally {await page?.close();await server.close();}

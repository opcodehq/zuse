import assert from "node:assert/strict";
import { mkdirSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { createServer } from "vite";
import { openBrowser } from "./harness.mjs";

const app = fileURLToPath(new URL("..", import.meta.url));
const server = await createServer({ root: app, configFile: `${app}/vite.config.ts`, server: { host: "127.0.0.1", port: 0, open: false } });
await server.listen();
const captures = process.env.ZUSE_SUBAGENT_CAPTURES;
if (captures) mkdirSync(captures, { recursive: true });
let page;
try {
  page = await openBrowser(`http://127.0.0.1:${server.httpServer.address().port}/e2e/web-parity/fixture.html`);
  await page.waitFor("!!window.parity");
  await page.eval("parity.workspace(); parity.zapper()");
  await page.waitFor("!!document.querySelector('.cmp-subagents')");
  await page.eval("parity.subagents(['running', 'failed', 'done'])");
  await page.waitFor("document.querySelector('.cmp-subagents')?.textContent.includes('1 working · 1 failed · 1 complete')");
  await page.eval("document.querySelector('.cmp-subagents').focus()");
  await page.key("Enter");
  await page.waitFor("document.querySelectorAll('.zp-subagent-row').length === 3");
  assert.equal(await page.eval("document.querySelector('.cmp-subagents').closest('.cmp-tray') !== null"), true);
  assert.equal(await page.eval("document.querySelector('.cmp-subagents').getBoundingClientRect().bottom <= document.querySelector('.cmp-card').getBoundingClientRect().top"), true);
  await page.eval("document.activeElement.blur()");
  if (captures) await page.screenshot(`${captures}/web-multiple-overview.png`);
  await page.press('.zp-subagent-row');
  await page.waitFor("document.body.textContent.includes('The desktop picker uses') && !!document.querySelector('.ws-agent-transcript')");
  assert.equal(await page.eval("!!document.querySelector('.ws-agent-list')"), false);
  await page.press('.cmp-subagents');
  await page.waitFor("document.querySelectorAll('.zp-subagent-row').length === 3");
  await page.eval("parity.subagents(['done'])");
  await page.waitFor("document.querySelector('.cmp-subagent-status')?.textContent === 'Review keyboard navigation · Complete'");
  if (captures) await page.screenshot(`${captures}/web-single-complete.png`);
  await page.eval("parity.subagentSession('idle'); new Promise(resolve => setTimeout(resolve, 300)).then(() => parity.subagents(['running']))");
  await page.waitFor("document.querySelector('.cmp-subagent-status')?.textContent === 'Review keyboard navigation · Working'");
  if (captures) await page.screenshot(`${captures}/web-waiting-parent.png`);
  await page.eval("parity.subagentSession('awaitingInput'); new Promise(resolve => setTimeout(resolve, 300)).then(() => parity.subagents(['running']))");
  assert.equal(await page.eval("document.querySelector('.cmp-subagent-status').textContent"), "Review keyboard navigation · Working");
  await page.eval("parity.subagentSession('idle', false); new Promise(resolve => setTimeout(resolve, 300)).then(() => parity.subagents(['running']))");
  await page.waitFor("document.querySelector('.cmp-subagent-status')?.textContent === 'Last known: Review keyboard navigation · Working'");
  await page.eval("parity.subagentSession('idle')");
  await page.call("Emulation.setDeviceMetricsOverride", { width: 390, height: 844, deviceScaleFactor: 1, mobile: false });
  await page.press('[aria-label="Close Zapper inspector"]');
  await page.eval("parity.subagents(['running', 'failed', 'done'])");
  await page.waitFor("document.querySelector('.cmp-subagents')?.getBoundingClientRect().width > 0");
  assert.equal(await page.eval("document.querySelector('.cmp-subagents').scrollWidth <= document.querySelector('.cmp-subagents').clientWidth"), true);
  assert.equal(await page.eval("document.documentElement.scrollWidth <= window.innerWidth"), true);
  if (captures) await page.screenshot(`${captures}/web-narrow-summary.png`);
  await page.press('.cmp-subagents');
  await page.waitFor("document.querySelector('.zp-inspector')?.getBoundingClientRect().width > 0");
  if (captures) await page.screenshot(`${captures}/web-narrow-overview.png`);
  await page.eval("parity.subagents([])");
  await page.waitFor("!document.querySelector('.cmp-subagents')");
  await page.call("Emulation.setDeviceMetricsOverride", { width: 1440, height: 900, deviceScaleFactor: 1, mobile: false });
  await page.waitFor("document.body.textContent.includes('No subagents in this conversation yet.')");
  if (captures) await page.screenshot(`${captures}/web-empty-overview.png`);
  await page.eval("parity.subagents(['running', 'failed', 'done']); document.documentElement.dataset.theme = 'dark'");
  await page.waitFor("document.querySelectorAll('.zp-subagent-row').length === 3");
  if (captures) await page.screenshot(`${captures}/web-dark-overview.png`);
  assert.deepEqual(page.errors, []);
  console.log("PASS integrated placement, keyboard Overview navigation, counts, agent details, empty/single/multiple states and narrow layout");
} finally { await page?.close(); await server.close(); }

import assert from 'node:assert/strict';
import { createServer } from 'vite';
import { openBrowser } from './harness.mjs';
const root=new URL('..',import.meta.url).pathname;
const server=await createServer({root,configFile:`${root}/vite.config.ts`,server:{host:'127.0.0.1',port:0,hmr:{overlay:false}}});
await server.listen();
let page;
try {
 page=await openBrowser(`http://127.0.0.1:${server.httpServer.address().port}/e2e/web-parity/fixture.html`);
 await page.waitFor('!!window.parity');
 await page.eval('parity.workspace(); parity.newChatPicker()');
 await page.waitFor("!!document.querySelector('.cmp-model')");
 await page.click('.cmp-model');
 await page.waitFor("document.querySelectorAll('.cmp-model-row').length === 4 && !!document.querySelector('.cmp-model-detail')");
 assert.equal(await page.eval("document.querySelectorAll('.cmp-detail-context').length"),0,'no context switch without an offered context option');
 await page.eval("[...document.querySelectorAll('.cmp-model-row')].find(row=>row.textContent.includes('Opus 4.6')).dispatchEvent(new MouseEvent('mousemove',{bubbles:true}))");
 await page.waitFor("document.querySelector('.cmp-detail-header')?.textContent.includes('Opus 4.6') && document.querySelectorAll('.cmp-detail-context button').length === 2");
 assert.equal(await page.eval("Math.round(document.querySelector('.cmp-model-detail').getBoundingClientRect().width)"),240);
 await page.eval("[...document.querySelectorAll('.cmp-detail-context button')].find(button=>button.textContent==='1M').click()");
 await page.waitFor("parity.pickerState().draft.model === 'claude-opus-4-6' && parity.pickerState().defaults.options['claude-code|claude-opus-4-6']?.contextWindow === '1m'");
 await page.eval("document.querySelector('.cmp-detail-context button[aria-checked=true]').focus()");
 await page.key('ArrowLeft','ArrowLeft',37);
 await page.waitFor("document.querySelector('.cmp-detail-context button[aria-checked=true]')?.textContent === '200K'");
 await page.key('ArrowRight','ArrowRight',39);
 await page.waitFor("document.querySelector('.cmp-detail-context button[aria-checked=true]')?.textContent === '1M'");
 await page.click('.cmp-model-detail [aria-label="Fast mode"]');
 await page.waitFor("document.querySelector('.cmp-model-detail [aria-label=\"Fast mode\"]')?.getAttribute('aria-pressed') === 'true'");
 await page.click('.cmp-model-detail [aria-label="Favorite"]');
 await page.waitFor("parity.pickerState().defaults.favorites.includes('claude-code|claude-opus-4-6') && document.querySelector('.cmp-models-list')?.textContent.includes('Favorites')");
 await page.click('.cmp-model-detail [aria-label="Default model"]');
 await page.waitFor("parity.pickerState().explicit?.model === 'claude-opus-4-6'");
 await page.click('.cmp-model-detail [aria-label="Default model"]');
 await page.waitFor("parity.pickerState().explicit === null && parity.pickerState().draft.model === 'claude-opus-4-6'");
 await page.eval("document.querySelector('.cmp-model-detail [role=slider]').focus()");
 await page.key('Home','Home',36);
 await page.waitFor("parity.pickerState().draft.reasoning === 'low'");
 const geometry = await page.eval("(() => { const slider=document.querySelector('.cmp-effort');const size=selector=>{const rect=slider.querySelector(selector).getBoundingClientRect();return [rect.width,rect.height]};return {height:slider.getBoundingClientRect().height,track:size('.cmp-effort-track'),knob:size('.cmp-effort-thumb'),fill:size('.cmp-effort-fill'),dots:[...slider.querySelectorAll('.cmp-effort-stops > span')].filter(dot=>getComputedStyle(dot).visibility==='visible').length,texture:!!slider.querySelector('.cmp-effort-texture rect')};})()");
 assert.equal(geometry.height,24);
 assert.equal(geometry.track[1],20);
 assert.deepEqual(geometry.knob,[22,14]);
 assert.equal(geometry.fill[0],23);
 assert.equal(geometry.dots,2);
 assert.equal(geometry.texture,true);
 await page.key('End','End',35);
 await page.waitFor("parity.pickerState().draft.reasoning === 'high'");
 console.log('PASS desktop model detail width, hovered model settings, catalog-only context, fast/favorite/default toggles, default clearing and reasoning keyboard control');
} finally {await page?.close(); await server.close();}
